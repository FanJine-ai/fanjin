import type { Knex } from "knex";
import { GenerationReferenceError } from "@/lib/generationReferenceError";
import { PortraitAdmissionWorkflowError } from "@/lib/portraitAdmissionError";
import { PortraitProviderRuntimeError } from "@/lib/portraitProviderError";
import { VideoAssetPolicyError } from "@/lib/videoAssetPolicy";
import { VideoPricingEstimateError } from "@/lib/videoTokenReservation";
import { ToolError } from "./contracts";

export class VideoGenerationNotStartedError extends Error {
  readonly code: string;
  constructor(cause: unknown) {
    const safe = cause instanceof ToolError || cause instanceof GenerationReferenceError
      || cause instanceof PortraitAdmissionWorkflowError || cause instanceof PortraitProviderRuntimeError
      || cause instanceof VideoAssetPolicyError;
    super(cause instanceof VideoPricingEstimateError ? cause.message : safe ? `${cause.message} 本次未冻结或扣费。`
      : "生成在提交上游前失败，本次未冻结或扣费。请检查素材和参数。");
    const code = (cause as { code?: unknown } | null)?.code;
    this.code = typeof code === "string" && /^[A-Za-z][A-Za-z0-9_-]{2,99}$/u.test(code)
      ? code : "GENERATION_NOT_DISPATCHED";
  }
}

/** Video dispatch and billing require a durable relay row first. Never use this for images. */
export async function hasToolVideoDispatchEvidence(database: Knex, taskId: string): Promise<boolean> {
  // These IDs are generated by the server; refuse wildcard/prefix ambiguity.
  if (!/^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/iu.test(taskId)) return true;
  const requestId = `tools:${taskId}`;
  const matchingRequest = (query: Knex.QueryBuilder) => query
    .where("requestId", requestId).orWhere("requestId", "like", `${requestId}:scope:%`);
  if (await database("o_relay_task").where(matchingRequest).first("id")) return true;
  // Defensive checks for inconsistent/orphaned billing data. Any evidence keeps reconciliation required.
  if (await database("o_billing_ledger").where(matchingRequest)
    .orWhere("relatedTaskId", taskId).first("id")) return true;
  if (await database("o_billing_reconcile_job").where(matchingRequest).first("id")) return true;
  if (await database("o_usage_record").where({ taskId }).first("id")) return true;
  return false;
}

export async function runToolVideoGeneration<T>(database: Knex, taskId: string, generate: () => Promise<T>): Promise<T> {
  try {
    return await generate();
  } catch (error) {
    let evidence = true;
    try { evidence = await hasToolVideoDispatchEvidence(database, taskId); } catch { /* An unavailable database cannot prove non-dispatch. */ }
    if (!evidence) throw new VideoGenerationNotStartedError(error);
    throw error;
  }
}
