export function parseVolcengineVideoAuditResult(input: {
  result: Record<string, unknown>; dataId: string; taskId: string; sourceUrlHash: string;
}): VolcengineVideoAuditPollResult {
  const { dataId, taskId } = input;
  const results = input.result.Results;
  const haveMore = input.result.HaveMore;
  const rawMarker = input.result.Marker;
  const nextMarker = rawMarker == null || rawMarker === ""
    ? ""
    : safeOpaqueToken(rawMarker, "VOLC_IMAGEX_MARKER_INVALID", 512, "response_received");
  if (!Array.isArray(results) || typeof haveMore !== "boolean" || (haveMore && !nextMarker)) {
    throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 视频审核轮询响应格式无效", "response_received");
  }
  if (results.length === 0) {
    return Object.freeze({
      dataId,
      decision: "pending",
      haveMore,
      marker: nextMarker || null,
      problemCount: 0,
      status: "pending",
      taskId,
    });
  }
  if (results.length !== 1 || !isPlainObject(results[0])) {
    throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 视频审核轮询响应数量无效", "response_received");
  }
  const item = results[0];
  // EntryId is generated by ImageX, not the caller's DataId. Bind the
  // response to the persisted task AND exact submitted URL digest.
  const uri = typeof item.Uri === "string" ? item.Uri : "";
  if (item.TaskId !== taskId || item.Type !== "Url"
    || !/^[a-f0-9]{64}$/.test(input.sourceUrlHash)
    || crypto.createHash("sha256").update(uri).digest("hex") !== input.sourceUrlHash) {
    throw reviewError("VOLC_IMAGEX_SCOPE_MISMATCH", "ImageX 视频审核响应绑定不一致", "response_received");
  }
  const auditResultType = cleanString(item.AuditResultType);
  const auditSuggestion = cleanString(item.AuditSuggestion);
  const upstreamErrorMessage = cleanString(item.ErrMsg);
  if (!(["normal", "problem", "frozen", "fail"] as const).includes(
    auditResultType as "normal" | "problem" | "frozen" | "fail",
  )) {
    throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 视频审核结果类型无效", "response_received");
  }
  if (auditSuggestion && !(["pass", "nopass", "recheck"] as const).includes(
    auditSuggestion as "pass" | "nopass" | "recheck",
  )) {
    throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 视频审核建议无效", "response_received");
  }
  // ImageX has returned Problems as null, [], a JSON string, a single object,
  // and arrays containing non-object rows across service versions. The
  // decision fields above are authoritative for pass/deny; only count problems
  // we can actually read. A shape quirk must not strand an otherwise complete
  // audit as "问题列表无效".
  const problems = normalizeVideoAuditProblems(item.Problems);
  let decision: VolcengineVideoAuditPollResult["decision"];
  if (auditResultType === "fail" && !auditSuggestion) decision = "failed";
  else if (auditSuggestion === "recheck") decision = "review";
  else if (
    auditResultType === "normal"
    && auditSuggestion === "pass"
    && !upstreamErrorMessage
    && problems.length === 0
  ) decision = "allow";
  else if (
    (auditResultType === "problem" || auditResultType === "frozen")
    && auditSuggestion === "nopass"
  ) decision = "deny";
  else {
    throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 视频审核结果组合无效", "response_received");
  }
  return Object.freeze({
    dataId,
    decision,
    haveMore,
    marker: nextMarker || null,
    problemCount: problems.length,
    status: "complete",
    taskId,
  });
}

function normalizeVideoAuditProblems(raw: unknown): Array<Record<string, unknown>> {
  let value = raw;
  if (value == null) return [];
  if (typeof value === "string") {
    const text = value.trim();
    if (!text) return [];
    try {
      value = JSON.parse(text);
    } catch {
      return [];
    }
  }
  if (Array.isArray(value)) {
    return value.filter(isPlainObject) as Array<Record<string, unknown>>;
  }
  if (isPlainObject(value)) {
    const nested = value.Problems ?? value.RiskList ?? value.List ?? value.Items;
    if (Array.isArray(nested)) {
      return nested.filter(isPlainObject) as Array<Record<string, unknown>>;
    }
    if (Object.keys(value).length === 0) return [];
    return [value];
  }
  return [];
}

export class VolcengineImageXReviewError extends Error {
  readonly code: string;
  readonly dispatchState: DispatchState;
  readonly httpStatus?: number;
  readonly upstreamCode?: string;
  readonly requestId?: string;

  constructor(input: {
    code: string;
    dispatchState?: DispatchState;
    httpStatus?: number;
    upstreamCode?: unknown;
    requestId?: unknown;
    message: string;
  }) {
    super(input.message);
    this.name = "VolcengineImageXReviewError";
    this.code = safeErrorCode(input.code);
    this.dispatchState = input.dispatchState ?? "not_dispatched";
    this.httpStatus = input.httpStatus;
    this.upstreamCode = safeDiagnosticIdentifier(input.upstreamCode);
    this.requestId = safeDiagnosticIdentifier(input.requestId);
  }
}

type RequestResult = Readonly<{
  result: Record<string, unknown>;
}>;

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function cleanString(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

function safeErrorCode(value: unknown): string {
  const code = cleanString(value);
  return /^[A-Za-z][A-Za-z0-9_.-]{0,127}$/u.test(code)
    ? code
    : "VOLC_IMAGEX_UPSTREAM_ERROR";
}

function safeDiagnosticIdentifier(value: unknown): string | undefined {
  return typeof value === "string" && /^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/u.test(value) && !value.startsWith("AKLT") ? value : undefined;
}

function reviewError(
  code: string,
  message: string,
  dispatchState: DispatchState = "not_dispatched",
): VolcengineImageXReviewError {
  return new VolcengineImageXReviewError({ code, dispatchState, message });
}

function safeOpaqueToken(
  value: unknown,
  code: string,
  maximum: number,
  dispatchState: DispatchState = "not_dispatched",
): string {
  if (
    typeof value !== "string"
    || !value
    || value !== value.trim()
    || value.length > maximum
    || /[\u0000-\u001f\u007f]/u.test(value)
  ) throw reviewError(code, "ImageX 安全预检配置无效", dispatchState);
  return value;
}

function safeIdentifier(value: unknown, code: string, maximum = 256): string {
  const token = safeOpaqueToken(value, code, maximum);
  if (!/^[A-Za-z0-9][A-Za-z0-9._:-]*$/u.test(token)) {
    throw reviewError(code, "ImageX 安全预检标识无效");
  }
  return token;
}

function safeDataId(value: unknown): string {
  const dataId = safeOpaqueToken(value, "VOLC_IMAGEX_DATA_ID_INVALID", 128);
  if (!/^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$/u.test(dataId)) {
    throw reviewError("VOLC_IMAGEX_DATA_ID_INVALID", "ImageX 安全预检 DataId 无效");
  }
  return dataId;
}

function safeHttpsUrl(value: unknown): string {
  const text = safeOpaqueToken(value, "VOLC_IMAGEX_URL_INVALID", 4_096);
  let parsed: URL;
  try {
    parsed = new URL(text);
  } catch {
    throw reviewError("VOLC_IMAGEX_URL_INVALID", "ImageX 安全预检素材地址无效");
  }
  if (
    parsed.protocol !== "https:"
    || parsed.username
    || parsed.password
    || parsed.hash
    || !parsed.hostname
  ) throw reviewError("VOLC_IMAGEX_URL_INVALID", "ImageX 安全预检素材地址必须是 HTTPS URL");
  return parsed.toString();
}

function requestTimeout(value: unknown): number {
  const parsed = value === undefined ? DEFAULT_TIMEOUT_MS : Number(value);
  if (!Number.isSafeInteger(parsed) || parsed < 1 || parsed > MAX_TIMEOUT_MS) {
    throw reviewError("VOLC_IMAGEX_TIMEOUT_INVALID", "ImageX 安全预检超时配置无效");
  }
  return parsed;
}

function providerMetadataError(payload: Record<string, unknown>): Record<string, unknown> | null {
  const metadata = payload.ResponseMetadata;
  if (!isPlainObject(metadata)) return null;
  const candidate = metadata.Error;
  return isPlainObject(candidate) ? candidate : null;
}

async function boundedResponseText(response: Response): Promise<string> {
  const declared = response.headers.get("content-length");
  if (declared !== null) {
    const length = Number(declared);
    if (!Number.isSafeInteger(length) || length < 0 || length > MAX_RESPONSE_BYTES) {
      throw new VolcengineImageXReviewError({
        code: "VOLC_IMAGEX_RESPONSE_TOO_LARGE",
        dispatchState: "response_received",
        httpStatus: response.status,
        message: "ImageX 安全预检响应超过安全大小限制",
      });
    }
  }
  if (!response.body) return "";
  const reader = response.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      total += value.byteLength;
      if (total > MAX_RESPONSE_BYTES) {
        await reader.cancel();
        throw new VolcengineImageXReviewError({
          code: "VOLC_IMAGEX_RESPONSE_TOO_LARGE",
          dispatchState: "response_received",
          httpStatus: response.status,
          message: "ImageX 安全预检响应超过安全大小限制",
        });
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  const merged = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    merged.set(chunk, offset);
    offset += chunk.byteLength;
  }
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(merged);
  } catch {
    throw new VolcengineImageXReviewError({
      code: "VOLC_IMAGEX_RESPONSE_INVALID",
      dispatchState: "response_received",
      httpStatus: response.status,
      message: "ImageX 安全预检响应编码无效",
    });
  }
}

function resolveCredential(
  channel: VolcengineImageXReviewProviderChannel,
  config: Record<string, unknown>,
): ProviderChannelImageXReviewCredential {
  for (const forbidden of [
    "imagexServiceId",
    "imagexAccessKeyId",
    "imagexSecretAccessKey",
    "imagexSessionToken",
    "accessKeyId",
    "secretAccessKey",
    "sessionToken",
  ]) {
    if (cleanString(config[forbidden])) {
      throw reviewError(
        "VOLC_IMAGEX_INLINE_CREDENTIAL_FORBIDDEN",
        "ImageX 安全预检凭据必须通过独立密文槽注入",
      );
    }
  }
  const requested = cleanString(channel.imagexReviewCredentialPlaintext);
  const transient = requested ? parseProviderChannelImageXReviewCredential(requested) : null;
  if (requested && !transient) {
    throw reviewError("VOLC_IMAGEX_CREDENTIAL_INVALID", "ImageX 安全预检请求凭据无效");
  }
  const inspected = inspectProviderChannelImageXReviewCredential(channel.id, config);
  const credential = transient ?? (inspected.configured ? inspected.credential : null);
  if (!inspected.enabled || !credential) {
    throw reviewError("VOLC_IMAGEX_CREDENTIAL_MISSING", "ImageX 安全预检独立凭据未配置或未启用");
  }
  return credential;
}

export class VolcengineImageXReviewClient {
  readonly channelId: string;
  readonly credentialGeneration: number;

  private readonly credential: ProviderChannelImageXReviewCredential;
  private readonly fetchFn: VolcengineImageXReviewFetch;
  private readonly now: () => number;
  private readonly timeoutMs: number;

  private constructor(input: {
    channelId: string;
    credential: ProviderChannelImageXReviewCredential;
    credentialGeneration: number;
    options: VolcengineImageXReviewClientOptions;
  }) {
    this.channelId = input.channelId;
    this.credential = input.credential;
    this.credentialGeneration = input.credentialGeneration;
    this.fetchFn = input.options.fetch ?? fetch;
    this.now = input.options.now ?? (() => Date.now());
    this.timeoutMs = requestTimeout(input.options.timeoutMs);
  }

  static fromProviderChannel(
    channel: VolcengineImageXReviewProviderChannel,
    options: VolcengineImageXReviewClientOptions = {},
  ): VolcengineImageXReviewClient {
    // ImageX uses a dedicated AK/SK slot rather than the ordinary Relay API
    // key resolver, so it must explicitly participate in Preview's global
    // no-provider dispatch gate before inspecting that credential.
    assertProviderDispatchAllowed();
    const channelId = safeIdentifier(channel.id, "VOLC_IMAGEX_CHANNEL_INVALID");
    if (cleanString(channel.provider).toLowerCase() !== "volcano") {
      throw reviewError("VOLC_IMAGEX_PROVIDER_INVALID", "ImageX 安全预检通道必须使用 Volcano provider");
    }
    if (channel.endpointType && cleanString(channel.endpointType) !== "video_generation") {
      throw reviewError("VOLC_IMAGEX_ENDPOINT_INVALID", "ImageX 安全预检通道必须是视频生成能力");
    }
    const config = {
      ...parseProviderChannelConfig(channel.configJson),
      ...(channel.config ?? {}),
    };
    const inspected = inspectProviderChannelImageXReviewCredential(channelId, config);
    const credential = resolveCredential(channel, config);
    return new VolcengineImageXReviewClient({
      channelId,
      credential,
      credentialGeneration: inspected.generation,
      options,
    });
  }

  async detectImageFaces(input: {
    imageUri: string;
    signal?: AbortSignal;
  }): Promise<VolcengineImageFaceResult> {
    const imageUri = safeHttpsUrl(input.imageUri);
    const response = await this.request("GetImageDetectResult", {
      body: {
        ImageUri: imageUri,
        DetectType: "face",
        FaceDetectThresh: FACE_DETECT_THRESHOLD,
      },
      query: { ServiceId: this.credential.serviceId },
      signal: input.signal,
    });
    const detectType = cleanString(response.result.DetectType);
    const faces = response.result.Faces;
    if (detectType !== "face" || !Array.isArray(faces) || faces.length > 10_000) {
      throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 人脸检测响应格式无效", "response_received");
    }
    if (faces.some((face) => !isPlainObject(face))) {
      throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 人脸检测响应格式无效", "response_received");
    }
    return Object.freeze({
      classification: faces.length === 0 ? "none" : faces.length === 1 ? "single" : "multiple",
      faceCount: faces.length,
    });
  }

  async auditImage(input: {
    dataId: string;
    imageUri: string;
    signal?: AbortSignal;
  }): Promise<VolcengineImageAuditResult> {
    const dataId = safeDataId(input.dataId);
    const imageUri = safeHttpsUrl(input.imageUri);
    const response = await this.request("SingleImageAudit", {
      body: {
        AuditAbility: 1,
        AuditDimensions: IMAGE_AUDIT_DIMENSIONS,
        Async: 0,
        DataId: dataId,
        ImageUri: imageUri,
      },
      query: { ServiceId: this.credential.serviceId },
      signal: input.signal,
    });
    if (response.result.DataId !== dataId || response.result.ImageUri !== imageUri) {
      throw reviewError("VOLC_IMAGEX_SCOPE_MISMATCH", "ImageX 图片审核响应绑定不一致", "response_received");
    }
    const imageType = cleanString(response.result.ImageType);
    const advice = cleanString(response.result.Advice);
    if (!(["normal", "problem"] as const).includes(imageType as "normal" | "problem")) {
      throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 图片审核响应格式无效", "response_received");
    }
    if (advice && advice !== "block" && advice !== "review") {
      throw reviewError("VOLC_IMAGEX_RESPONSE_INVALID", "ImageX 图片审核建议无效", "response_received");
    }
    const normalizedImageType = imageType as "normal" | "problem";
    const normalizedAdvice = advice ? advice as "block" | "review" : null;
    const decision = normalizedImageType === "normal" && normalizedAdvice === null
      ? "allow" as const
      : "deny" as const;
    return Object.freeze({ advice: normalizedAdvice, decision, imageType: normalizedImageType });
  }

  async createVideoAuditTask(input: {
    dataId: string;
    signal?: AbortSignal;
    videoUri: string;
  }): Promise<VolcengineVideoAuditSubmission> {
    const dataId = safeDataId(input.dataId);
    const videoUri = safeHttpsUrl(input.videoUri);
    const response = await this.request("CreateVideoAuditTask", {
      body: {
        AuditAbility: 1,
        AuditDimensions: VIDEO_AUDIT_DIMENSIONS,
        EnableCallback: false,
        EnableFreeze: false,
        ImageInfos: [{ DataId: dataId, ImageUri: videoUri }],
        Interval: 1,
        Region: IMAGEX_TASK_REGION,
        ServiceId: this.credential.serviceId,
        TaskType: "audit_video",
        Type: "Url",
      },
      mutation: true,
      signal: input.signal,
    });
    try {
      return Object.freeze({
        dataId,
        taskId: safeIdentifier(response.result.TaskId, "VOLC_IMAGEX_TASK_ID_INVALID"),
      });
    } catch (caught) {
      if (caught instanceof VolcengineImageXReviewError) {
        throw new VolcengineImageXReviewError({
          code: caught.code,
          dispatchState: "outcome_unknown",
          message: "ImageX 视频审核创建响应无效，结果未知",
        });
      }
      throw reviewError(
        "VOLC_IMAGEX_RESPONSE_INVALID",
        "ImageX 视频审核创建响应无效，结果未知",
        "outcome_unknown",
      );
    }
  }

  async getVideoAuditResult(input: {
    sourceUrlHash: string;
    dataId: string;
    limit?: number;
    marker?: string;
    signal?: AbortSignal;
    taskId: string;
  }): Promise<VolcengineVideoAuditPollResult> {
    const dataId = safeDataId(input.dataId);
    const taskId = safeIdentifier(input.taskId, "VOLC_IMAGEX_TASK_ID_INVALID");
    const limit = input.limit === undefined ? 100 : Number(input.limit);
    if (!Number.isSafeInteger(limit) || limit < 1 || limit > 100) {
      throw reviewError("VOLC_IMAGEX_LIMIT_INVALID", "ImageX 视频审核分页大小无效");
    }
    const marker = input.marker === undefined
      ? ""
      : safeOpaqueToken(input.marker, "VOLC_IMAGEX_MARKER_INVALID", 512);
    const response = await this.request("GetVideoAuditResult", {
      method: "GET",
      query: {
        Limit: String(limit),
        TaskId: taskId,
        Type: "Url",
        ...(marker ? { Marker: marker } : {}),
      },
      signal: input.signal,
    });
    return parseVolcengineVideoAuditResult({ result: response.result, dataId, taskId, sourceUrlHash: input.sourceUrlHash });
  }

  private async request(
    action: ImageXAction,
    input: {
      body?: Record<string, unknown>;
      method?: "GET" | "POST";
      mutation?: boolean;
      query?: Readonly<Record<string, string>>;
      signal?: AbortSignal;
    },
  ): Promise<RequestResult> {
    const method = input.method ?? "POST";
    const body = method === "POST" ? JSON.stringify(input.body ?? {}) : "";
    const query = { Action: action, Version: IMAGEX_VERSION, ...(input.query ?? {}) };
    const signInput = {
      accessKeyId: this.credential.accessKeyId,
      at: new Date(this.now()),
      host: IMAGEX_HOST,
      pathname: IMAGEX_PATHNAME,
      query,
      region: IMAGEX_API_REGION,
      secretAccessKey: this.credential.secretAccessKey,
      service: IMAGEX_SERVICE,
      ...(this.credential.sessionToken === undefined
        ? {}
        : { sessionToken: this.credential.sessionToken }),
    };
    const signed = method === "POST"
      ? signVolcengineV4JsonPost({ ...signInput, body })
      : signVolcengineV4Get(signInput);
    const url = `https://${IMAGEX_HOST}${IMAGEX_PATHNAME}?${signed.canonicalQuery}`;
    if (input.signal?.aborted) {
      throw reviewError("VOLC_IMAGEX_ABORTED", "ImageX 安全预检请求已取消");
    }
    const controller = new AbortController();
    let timedOut = false;
    let dispatched = false;
    const timer = setTimeout(() => {
      timedOut = true;
      controller.abort();
    }, this.timeoutMs);
    const abort = () => controller.abort();
    input.signal?.addEventListener("abort", abort, { once: true });
    try {
      dispatched = true;
      const response = await this.fetchFn(url, {
        ...(method === "POST" ? { body } : {}),
        cache: "no-store",
        credentials: "omit",
        headers: signed.headers,
        method,
        redirect: "error",
        signal: controller.signal,
      });
      const text = await boundedResponseText(response);
      let errorPayload: any = null;
      try { errorPayload = JSON.parse(text); } catch { /* Non-JSON errors carry no replay-safe evidence. */ }
      if (!response.ok) {
        throw new VolcengineImageXReviewError({
          code: `VOLC_IMAGEX_HTTP_${response.status}`,
          dispatchState: input.mutation ? "outcome_unknown" : "response_received",
          httpStatus: response.status,
          upstreamCode: errorPayload?.ResponseMetadata?.Error?.Code,
          requestId: errorPayload?.ResponseMetadata?.RequestId,
          message: "ImageX 安全预检服务拒绝了请求",
        });
      }
      let payload: unknown;
      try {
        payload = JSON.parse(text);
      } catch {
        throw new VolcengineImageXReviewError({
          code: "VOLC_IMAGEX_RESPONSE_INVALID",
          dispatchState: input.mutation ? "outcome_unknown" : "response_received",
          httpStatus: response.status,
          message: "ImageX 安全预检响应不是有效 JSON",
        });
      }
      if (!isPlainObject(payload)) {
        throw new VolcengineImageXReviewError({
          code: "VOLC_IMAGEX_RESPONSE_INVALID",
          dispatchState: input.mutation ? "outcome_unknown" : "response_received",
          httpStatus: response.status,
          message: "ImageX 安全预检响应格式无效",
        });
      }
      const providerError = providerMetadataError(payload);
      if (providerError) {
        throw new VolcengineImageXReviewError({
          code: "VOLC_IMAGEX_UPSTREAM_REJECTED",
          dispatchState: input.mutation ? "outcome_unknown" : "response_received",
          httpStatus: response.status,
          upstreamCode: providerError.Code,
          requestId: (payload.ResponseMetadata as any)?.RequestId,
          message: "ImageX 安全预检服务拒绝了请求",
        });
      }
      if (!isPlainObject(payload.Result)) {
        throw new VolcengineImageXReviewError({
          code: "VOLC_IMAGEX_RESPONSE_INVALID",
          dispatchState: input.mutation ? "outcome_unknown" : "response_received",
          httpStatus: response.status,
          message: "ImageX 安全预检响应缺少结果",
        });
      }
      return Object.freeze({ result: payload.Result });
    } catch (caught) {
      if (caught instanceof VolcengineImageXReviewError) {
        if (input.mutation && caught.dispatchState === "response_received") {
          throw new VolcengineImageXReviewError({
            code: caught.code,
            dispatchState: "outcome_unknown",
            httpStatus: caught.httpStatus,
            upstreamCode: caught.upstreamCode,
            requestId: caught.requestId,
            message: caught.message,
          });
        }
        throw caught;
      }
      const beforeDispatch = !dispatched;
      const outcomeUnknown = Boolean(input.mutation && !beforeDispatch);
      if (timedOut) {
        throw reviewError(
          "VOLC_IMAGEX_TIMEOUT",
          "ImageX 安全预检请求超时",
          outcomeUnknown ? "outcome_unknown" : "not_dispatched",
        );
      }
      if (input.signal?.aborted) {
        throw reviewError(
          "VOLC_IMAGEX_ABORTED",
          "ImageX 安全预检请求已取消",
          outcomeUnknown ? "outcome_unknown" : "not_dispatched",
        );
      }
      throw reviewError(
        "VOLC_IMAGEX_TRANSPORT_FAILED",
        "ImageX 安全预检网络请求失败",
        outcomeUnknown ? "outcome_unknown" : beforeDispatch ? "not_dispatched" : "response_received",
      );
    } finally {
      clearTimeout(timer);
      input.signal?.removeEventListener("abort", abort);
    }
  }
}

export function createVolcengineImageXReviewClient(
  channel: VolcengineImageXReviewProviderChannel,
  options: VolcengineImageXReviewClientOptions = {},
): VolcengineImageXReviewClient {
  return VolcengineImageXReviewClient.fromProviderChannel(channel, options);
}
